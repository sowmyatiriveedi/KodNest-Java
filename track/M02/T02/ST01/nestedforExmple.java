package track.M02.T02.ST01;

public class nestedforExmple {
    public static void main(String[] args) {
        int i, j;
        for (i = 1; i <= 5; i++) {
            for (j = 1; j <= 5; j++) {
                System.out.println(j);
            }
            System.out.println();
        }
    }
}
